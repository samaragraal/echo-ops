import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 432, height: 768 }, deviceScaleFactor: 2 });
const errors = [];
page.on('pageerror', e => errors.push(String(e)));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('http://localhost:5199/');
await page.waitForTimeout(1200);
await page.screenshot({ path: 'shots/menu.png' });
await page.click('.hero:nth-child(2)');
await page.click('button.play');
await page.waitForTimeout(500);
const st = () => page.evaluate(() => { const g = window.__game(); const p = g.player; return { x: Math.round(p.x), y: Math.round(p.y), f: +p.facing.toFixed(2), hero: p.hero.id, cd: +p.abilityCd.toFixed(1), spread: +p.spread.toFixed(3) }; });
const a = await st();
await page.keyboard.down('KeyW'); await page.waitForTimeout(800); await page.keyboard.up('KeyW');
const b = await st();
await page.mouse.move(216, 400); await page.mouse.down(); await page.mouse.move(316, 400, { steps: 10 }); await page.mouse.up();
const c = await st();
await page.keyboard.press('Space');
await page.waitForTimeout(1200);
const d = await st();
console.log(JSON.stringify({ start: a, afterW: b, afterTurn: c, afterAbility: d }));
await page.screenshot({ path: 'shots/human.png' });
// touch emulation
const ctx2 = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 2 });
const m = await ctx2.newPage();
m.on('pageerror', e => errors.push('mobile ' + String(e)));
await m.goto('http://localhost:5199/?autostart');
await m.waitForTimeout(1200);
const ms = () => m.evaluate(() => { const p = window.__game().player; return { x: Math.round(p.x), y: Math.round(p.y), f: +p.facing.toFixed(2) }; });
const m0 = await ms();
const cdp = await ctx2.newCDPSession(m);
const touch = (type, pts) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: pts });
await touch('touchStart', [{ x: 100, y: 600 }]);
for (let i = 1; i <= 10; i++) { await touch('touchMove', [{ x: 100 + i * 6, y: 600 }]); await m.waitForTimeout(40); }
await m.waitForTimeout(900);
await m.screenshot({ path: 'shots/mobile.png' });
await touch('touchEnd', []);
const m1 = await ms();
console.log('mobile', JSON.stringify({ m0, m1 }), 'errors', errors);
await browser.close();
